#!/usr/bin/env python3
"""Build templates/engine.js from the readable modules in templates/engine/*.js (concatenated in file-name order).
Pages load ONE file (cp templates/engine.js <proj>/site/), so engine.js stays the shipped artifact — edit the modules,
then rebuild. All modules share one IIFE scope (01-header opens it, 18-footer closes it).
usage: build_engine.py            write templates/engine.js
       build_engine.py --check    exit 1 if engine.js is out of date (CI)
"""
import glob, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, OUT = os.path.join(ROOT, 'templates', 'engine'), os.path.join(ROOT, 'templates', 'engine.js')
BANNER = '/* GENERATED by scripts/build_engine.py from templates/engine/*.js — edit the modules, not this file. */\n'

def build():
    return BANNER + ''.join(open(f, encoding='utf-8').read() for f in sorted(glob.glob(os.path.join(SRC, '*.js'))))

if __name__ == '__main__':
    out = build()
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if cur != out: sys.exit('templates/engine.js is out of date → python3 scripts/build_engine.py')
        print('engine.js up to date'); sys.exit(0)
    open(OUT, 'w', encoding='utf-8').write(out); print(f'wrote {os.path.relpath(OUT, ROOT)} ({len(out)} bytes)')
